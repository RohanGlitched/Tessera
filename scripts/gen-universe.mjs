// Generates web/lib/universe.ts from live Jupiter + Pyth data.
// Re-run this when Backed lists new xStocks.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const OUT = resolve(import.meta.dirname, "../web/lib/universe.ts");

// Company names Jupiter reports as "<Company> xStock"; a few need a nicer label.
const NICE = {
  SPYx: "S&P 500",
  QQQx: "Nasdaq 100",
  GLDx: "Gold",
  SPCXx: "SpaceX",
  DFDVx: "DeFi Development",
  STRCx: "Strategy (STRC)",
  MSTRx: "Strategy",
  CRCLx: "Circle",
  HOODx: "Robinhood",
  GMEx: "GameStop",
  MCDx: "McDonald's",
  PLTRx: "Palantir",
  GOOGLx: "Alphabet",
  METAx: "Meta",
  AMZNx: "Amazon",
  COINx: "Coinbase",
};

// A curated mosaic palette. Hues are assigned per-ticker and never change, so a
// ticker keeps the same tile colour everywhere in the product.
const HUES = [
  "#C9A227", // gold
  "#2E7D6B", // malachite
  "#9E3B32", // porphyry
  "#3E6BE0", // lapis
  "#7A5CA8", // amethyst
  "#B4703A", // sienna
  "#4A8FA8", // turquoise
  "#8A9A3F", // olive
  "#A8456B", // rose
  "#5C6B8A", // slate
];

async function j(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

console.log("fetching Jupiter xStock list…");
const jup = await j("https://lite-api.jup.ag/tokens/v2/search?query=xStock");
const tokens = (Array.isArray(jup) ? jup : jup.tokens || []).filter(
  (t) => t.tags?.includes("xstocks") || /xStock/i.test(t.name || ""),
);
if (tokens.length < 5) throw new Error(`only found ${tokens.length} xStocks`);

console.log("fetching Pyth feed catalogue…");
const feeds = await j("https://hermes.pyth.network/v2/price_feeds");
const bySymbol = new Map(feeds.map((f) => [f.attributes.symbol, f]));

const rows = tokens
  .map((t) => {
    const symbol = t.symbol;
    const base = symbol.replace(/x$/, "").toUpperCase();
    const equity = bySymbol.get(`Equity.US.${base}/USD`);
    const redemption = bySymbol.get(`Crypto.${base}X/${base}.RR`);
    const tokenised = bySymbol.get(`Crypto.${base}X/USD`);
    const company =
      NICE[symbol] ?? ((t.name || "").replace(/\s*xStock$/i, "").trim() || base);
    return {
      symbol,
      base,
      company,
      mint: t.id,
      decimals: t.decimals,
      equityFeedId: equity?.id ?? null,
      redemptionFeedId: redemption?.id ?? null,
      tokenisedFeedId: tokenised?.id ?? null,
      schedule: equity?.attributes?.schedule ?? null,
    };
  })
  .sort((a, b) => a.symbol.localeCompare(b.symbol));

rows.forEach((r, i) => (r.hue = HUES[i % HUES.length]));

const banner = `// GENERATED by scripts/gen-universe.mjs on ${new Date().toISOString()}
// Do not edit by hand. Mints and Pyth feed ids are read from Jupiter and Hermes.
`;

const body = `${banner}
export type XStock = {
  /** Ticker as Backed issues it, e.g. "AAPLx". */
  symbol: string;
  /** The underlying listed ticker, e.g. "AAPL". */
  base: string;
  company: string;
  /** Token-2022 mint on Solana mainnet. */
  mint: string;
  decimals: number;
  /** Pyth feed for the real listed share. Only priced during market hours. */
  equityFeedId: string | null;
  /** Pyth feed for the token's premium over the real share. Priced 24/7. */
  redemptionFeedId: string | null;
  /** Pyth feed for the token itself in USD. Priced 24/7. */
  tokenisedFeedId: string | null;
  /** Pyth trading-hours schedule string for the underlying listing. */
  schedule: string | null;
  /** Stable mosaic tile colour for this ticker. */
  hue: string;
};

export const XSTOCKS: XStock[] = ${JSON.stringify(rows, null, 2)};

export const BY_SYMBOL: Record<string, XStock> = Object.fromEntries(
  XSTOCKS.map((s) => [s.symbol, s]),
);

export const BY_MINT: Record<string, XStock> = Object.fromEntries(
  XSTOCKS.map((s) => [s.mint, s]),
);

/** USDC on Solana mainnet. */
export const USDC_MAINNET = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v";

export const TOKEN_2022_PROGRAM_ID = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb";
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`wrote ${rows.length} xStocks to ${OUT}`);
console.table(
  rows.map((r) => ({
    symbol: r.symbol,
    company: r.company,
    rr: r.redemptionFeedId ? "yes" : "—",
    eq: r.equityFeedId ? "yes" : "—",
  })),
);
